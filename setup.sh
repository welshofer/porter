#!/bin/bash
#
# Porter Setup Script
# Generates configuration files with correct paths for the current user
#
# Usage:
#   ./setup.sh              # Interactive setup
#   ./setup.sh --defaults   # Use defaults (no prompts)
#

set -e

# Detect environment
USER_NAME=$(whoami)
HOME_DIR="$HOME"
AGENT_DIR="$HOME/.claude/agents/porter"

# Colors
RED='\033[0;31m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
CYAN='\033[0;36m'
NC='\033[0m'

echo -e "${CYAN}"
echo "╔═══════════════════════════════════════════════════════════╗"
echo "║           Porter Setup                                ║"
echo "║   Reminder-Driven Autonomous Coding Agent                 ║"
echo "╚═══════════════════════════════════════════════════════════╝"
echo -e "${NC}"

echo -e "${GREEN}Detected:${NC}"
echo "  User:      $USER_NAME"
echo "  Home:      $HOME_DIR"
echo "  Agent Dir: $AGENT_DIR"
echo ""

# Check for required tools
echo -e "${CYAN}Checking dependencies...${NC}"
MISSING=()

if ! command -v python3 &> /dev/null; then
    MISSING+=("python3")
fi

if ! command -v gh &> /dev/null; then
    MISSING+=("gh (brew install gh)")
fi

if ! command -v claude &> /dev/null; then
    MISSING+=("claude (Claude Code CLI)")
fi

# Find reminders-cli
REMINDERS_BIN=""
if [ -f "$HOME/.local/bin/reminders-cli" ]; then
    REMINDERS_BIN="$HOME/.local/bin/reminders-cli"
elif command -v reminders &> /dev/null; then
    REMINDERS_BIN=$(which reminders)
else
    MISSING+=("reminders-cli (brew install keith/formulae/reminders-cli)")
fi

# Find claude
CLAUDE_BIN=""
if command -v claude &> /dev/null; then
    CLAUDE_BIN=$(which claude)
elif [ -f "/opt/homebrew/bin/claude" ]; then
    CLAUDE_BIN="/opt/homebrew/bin/claude"
fi

# Find gh
GH_BIN=""
if command -v gh &> /dev/null; then
    GH_BIN=$(which gh)
elif [ -f "/opt/homebrew/bin/gh" ]; then
    GH_BIN="/opt/homebrew/bin/gh"
fi

# Find imsg (optional)
IMSG_BIN=""
if [ -f "$HOME/.local/bin/imsg" ]; then
    IMSG_BIN="$HOME/.local/bin/imsg"
elif command -v imsg &> /dev/null; then
    IMSG_BIN=$(which imsg)
fi

if [ ${#MISSING[@]} -ne 0 ]; then
    echo -e "${RED}Missing required dependencies:${NC}"
    for dep in "${MISSING[@]}"; do
        echo "  - $dep"
    done
    echo ""
    echo "Please install them and run setup again."
    exit 1
fi

echo -e "${GREEN}All required dependencies found${NC}"
echo ""

# Interactive mode or defaults
INTERACTIVE=true
if [ "$1" == "--defaults" ]; then
    INTERACTIVE=false
fi

# Gather configuration
if [ "$INTERACTIVE" == true ]; then
    echo -e "${CYAN}Configuration${NC}"
    echo ""

    # Phone number for notifications
    read -p "Phone number for iMessage notifications (or blank to disable): " PHONE_NUMBER

    # PRD repo
    echo ""
    echo "PRDs are stored in a GitHub repo for easy review from any device."
    read -p "GitHub username for PRD repo [$(echo $USER_NAME)]: " GH_USER
    GH_USER=${GH_USER:-$USER_NAME}
    PRD_REPO="https://github.com/$GH_USER/prds"
    read -p "PRD repo URL [$PRD_REPO]: " PRD_REPO_INPUT
    PRD_REPO=${PRD_REPO_INPUT:-$PRD_REPO}

    # First project mapping
    echo ""
    echo "Map a Reminders list to a GitHub repo (you can add more in config.toml later)"
    read -p "Reminders list name (e.g., 'MyProject'): " PROJECT_NAME
    read -p "GitHub repo URL for '$PROJECT_NAME': " PROJECT_REPO
else
    PHONE_NUMBER=""
    GH_USER="$USER_NAME"
    PRD_REPO="https://github.com/$GH_USER/prds"
    PROJECT_NAME=""
    PROJECT_REPO=""
fi

echo ""
echo -e "${CYAN}Generating configuration files...${NC}"

# Create directories
mkdir -p "$AGENT_DIR/logs"
mkdir -p "$AGENT_DIR/workspaces"

# Generate config.toml
cat > "$AGENT_DIR/config.toml" << EOF
# Porter Configuration
# Reminder-Driven Autonomous Coding Agent
#
# Generated by setup.sh on $(date)

[daemon]
poll_interval_seconds = 300    # 5 minutes
max_concurrent_tasks = 1       # Process one task at a time
retry_max = 3                  # Max retries on failure
approval_timeout_days = 7      # Auto-reject if not approved within this time

[paths]
workspaces = "~/.claude/agents/porter/workspaces"
logs = "~/.claude/agents/porter/logs"
db = "~/.claude/agents/porter/state.db"

[prd_repo]
url = "$PRD_REPO"
local_path = "~/.claude/agents/porter/workspaces/prds"

[tools]
reminders_bin = "$REMINDERS_BIN"
claude_bin = "$CLAUDE_BIN"
gh_bin = "$GH_BIN"
imsg_bin = "$IMSG_BIN"

[notification]
phone_number = "$PHONE_NUMBER"
notify_on_prd_ready = true
notify_on_pr_created = true
notify_on_error = true

[reminders]
notes_fetch_mode = "applescript_fallback"
applescript_timeout_seconds = 5

[claude]
model = "opus"                      # "opus" for highest quality, "sonnet" for speed
timeout_seconds = 1800              # 30 min max per Claude invocation
permission_mode = "bypassPermissions"

# Project-to-repo mappings
# Key = Reminder list name (case-sensitive)
# Value = GitHub repo URL
#
# To add a new project:
# 1. Create a Reminders list with the project name
# 2. Add a mapping here: "ListName" = "https://github.com/user/repo"
# 3. Create tasks in that list with prefix "Task: "

[projects]
EOF

# Add project mapping if provided
if [ -n "$PROJECT_NAME" ] && [ -n "$PROJECT_REPO" ]; then
    echo "\"$PROJECT_NAME\" = \"$PROJECT_REPO\"" >> "$AGENT_DIR/config.toml"
else
    echo "# Add your project mappings here:" >> "$AGENT_DIR/config.toml"
    echo "# \"MyProject\" = \"https://github.com/username/repo\"" >> "$AGENT_DIR/config.toml"
fi

echo -e "${GREEN}Created:${NC} $AGENT_DIR/config.toml"

# Generate LaunchAgent plist
PLIST_NAME="com.$USER_NAME.porter"
cat > "$AGENT_DIR/$PLIST_NAME.plist" << EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
    <key>Label</key>
    <string>$PLIST_NAME</string>

    <key>ProgramArguments</key>
    <array>
        <string>/usr/bin/python3</string>
        <string>$AGENT_DIR/porter.py</string>
    </array>

    <key>StartInterval</key>
    <integer>300</integer>

    <key>WorkingDirectory</key>
    <string>$AGENT_DIR</string>

    <key>StandardOutPath</key>
    <string>$AGENT_DIR/logs/launchd_stdout.log</string>

    <key>StandardErrorPath</key>
    <string>$AGENT_DIR/logs/launchd_stderr.log</string>

    <key>EnvironmentVariables</key>
    <dict>
        <key>PATH</key>
        <string>/opt/homebrew/bin:/usr/local/bin:/usr/bin:/bin:$HOME/.local/bin</string>
        <key>HOME</key>
        <string>$HOME_DIR</string>
    </dict>

    <key>RunAtLoad</key>
    <false/>
</dict>
</plist>
EOF

echo -e "${GREEN}Created:${NC} $AGENT_DIR/$PLIST_NAME.plist"

# Update install.sh with correct plist name
sed -i '' "s/PLIST_NAME=\"com\\.welshofer\\.porter\\.plist\"/PLIST_NAME=\"$PLIST_NAME.plist\"/" "$AGENT_DIR/install.sh" 2>/dev/null || true
sed -i '' "s/com\\.welshofer\\.porter/$PLIST_NAME/g" "$AGENT_DIR/install.sh" 2>/dev/null || true

echo -e "${GREEN}Updated:${NC} $AGENT_DIR/install.sh"

# Remove old plist if different name
if [ -f "$AGENT_DIR/com.welshofer.porter.plist" ] && [ "$PLIST_NAME" != "com.welshofer.porter" ]; then
    rm "$AGENT_DIR/com.welshofer.porter.plist"
    echo -e "${YELLOW}Removed:${NC} old plist file"
fi

echo ""
echo -e "${GREEN}Setup complete!${NC}"
echo ""
echo -e "${CYAN}Next steps:${NC}"
echo ""
echo "1. Create the PRD repo on GitHub (if it doesn't exist):"
echo "   gh repo create prds --private"
echo ""
echo "2. Edit config.toml to add your project mappings:"
echo "   nano $AGENT_DIR/config.toml"
echo ""
echo "3. Install and start the agent:"
echo "   cd $AGENT_DIR"
echo "   ./install.sh install"
echo ""
echo "4. Create a task in Reminders:"
echo "   - Open Reminders app"
echo "   - Create a list matching your project name"
echo "   - Add a reminder: \"Task: Your feature description\""
echo ""
echo "5. Monitor the agent:"
echo "   ./install.sh logs"
echo ""
